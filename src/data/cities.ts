export function getCityBySlug(slug: string): CityInfo | undefined {
  return CITIES.find((c) => c.slug === slug.toLowerCase());
}

export function getAllCitySlugs(): string[] {
  return CITIES.map((c) => c.slug);
}

export function searchCitiesLocal(query: string): CityInfo[] {
  if (!query || query.trim().length === 0) return [];
  const q = query.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();

  return CITIES.filter((city) => {
    const nameNorm = city.name.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    const stateNorm = city.state.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    const ufNorm = city.uf.toLowerCase();

    return nameNorm.includes(q) || stateNorm.includes(q) || ufNorm === q;
  });
}
